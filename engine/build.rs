//! Registers custom plug-ins. Every `<name>.rs` in a plug-in folder becomes a
//! module and is added to its registry with no other edit:
//!
//!   src/formats/custom/  scanners (carvers)    -> `formats::all()`
//!   src/fs/custom/       volume readers        -> `fs::open()`
//!
//! Files whose name starts with `_` are ignored (the templates are such).

use std::{env, fs, path::Path};

fn names_in(dir: &Path) -> Vec<String> {
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut names: Vec<String> = fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|e| {
            let name = e.file_name().into_string().ok()?;
            let stem = name.strip_suffix(".rs")?;
            let ok = !stem.starts_with('_')
                && stem != "mod"
                && stem.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
            ok.then(|| stem.to_string())
        })
        .collect();
    names.sort();
    names
}

fn modules(dir: &Path, names: &[String]) -> String {
    let root = env::current_dir().unwrap();
    let mut out = String::from("// Generated by build.rs. Do not edit.\n");
    for n in names {
        let path = root.join(dir).join(format!("{n}.rs"));
        out += &format!(
            "#[path = {:?}]\n#[allow(dead_code)]\npub mod {n};\n",
            path.display().to_string()
        );
    }
    out
}

fn main() {
    let out_dir = env::var("OUT_DIR").unwrap();

    let dir = Path::new("src/formats/custom");
    let names = names_in(dir);
    let mut out = modules(dir, &names);
    out += "\n/// The custom scanners, in file-name order.\npub fn all() -> Vec<Box<dyn super::Format>> {\n    vec![\n";
    for n in &names {
        out += &format!("        {n}::format(),\n");
    }
    out += "    ]\n}\n\n/// Hand-made sample files for each scanner, for the damage tests.\n#[cfg(test)]\n#[allow(clippy::type_complexity)]\npub fn samples() -> Vec<(&'static str, Box<dyn super::Format>, Vec<Vec<u8>>)> {\n    vec![\n";
    for n in &names {
        out += &format!("        ({n:?}, {n}::format(), {n}::samples()),\n");
    }
    out += "    ]\n}\n";
    fs::write(Path::new(&out_dir).join("custom_formats.rs"), out).unwrap();

    let dir = Path::new("src/fs/custom");
    let names = names_in(dir);
    let mut out = modules(dir, &names);
    out += "\n/// The custom volume readers, in file-name order.\npub fn all() -> Vec<Box<dyn super::VolumeReader>> {\n    vec![\n";
    for n in &names {
        out += &format!("        {n}::reader(),\n");
    }
    out += "    ]\n}\n";
    fs::write(Path::new(&out_dir).join("custom_readers.rs"), out).unwrap();
}
